# frozen_string_literal: true

require 'digest'
require 'set'

module I18n
  module Collation
    class Error < I18n::ArgumentError; end
    CollationError = Error
    class InvalidTable < Error; end
    InvalidCollationTable = InvalidTable
    class InvalidString < Error; end
    InvalidCollationString = InvalidString
    class UndefinedWeight < Error; end
    UndefinedCollationWeight = UndefinedWeight
    class IncompatibleSortKey < Error; end
    IncompatibleConfiguration = IncompatibleSortKey
    IncompatibleCollation = IncompatibleSortKey
    IncompatibleCollationConfiguration = IncompatibleSortKey
    class MissingCollation < Error; end
    MissingCollationConfiguration = MissingCollation

    END_OF_RULE = :__i18n_collation_rule__

    class SortKey
      include Comparable

      attr_reader :fingerprint, :levels, :locale

      def initialize(fingerprint, levels, locale)
        @fingerprint = fingerprint
        @levels = levels.map(&:freeze).freeze
        @locale = locale
        @binary = levels.map { |level| level.pack('Q>*') }.join("\0").b
        freeze
      end

      def <=>(other)
        unless other.is_a?(SortKey) && other.fingerprint == fingerprint
          raise IncompatibleSortKey, 'sort keys were generated by incompatible collation configurations'
        end

        levels <=> other.levels
      end

      def to_a
        levels.map(&:dup)
      end

      def to_s
        @binary
      end
      alias_method :to_str, :to_s

      def inspect
        "#<#{self.class} locale=#{locale.inspect} levels=#{levels.inspect}>"
      end
    end
    Key = SortKey

    class Collator
      attr_reader :locale, :strength, :weights_version, :fingerprint

      def initialize(locale: :root, weights: {}, tailorings: nil, tailoring: nil,
                     strength: 3, numeric: false, ignore_punctuation: false)
        @locale = normalize_locale(locale)
        @strength = strength
        @numeric = numeric
        @ignore_punctuation = ignore_punctuation

        raise InvalidTable, 'strength must be 1, 2, or 3' unless [1, 2, 3].include?(@strength)

        weights = UCATable.load(weights) if weights.is_a?(::String) || weights.respond_to?(:to_path)
        weights ||= {}
        unless weights.is_a?(::Hash)
          raise InvalidTable, 'collation weights must be provided as a Hash or local allkeys file'
        end
        @weights_version = weights[:version] || 'custom'
        @variable_code_points = Set.new(extract_variables(weights))
        mappings = weights.key?(:mappings) ? weights[:mappings] : weights.except(:version, :variable, :variables)
        @weights = normalize_rules(mappings)

        tailorings = normalize_tailorings(tailorings)
        fallback = locale_fallback(@locale).last || :root
        tailorings[fallback] ||= {}
        tailorings[fallback] = tailorings[fallback].merge(normalize_rules(tailoring || {}))
        @tailorings = tailorings

        @selected_locale, selected_rules = select_tailoring(@locale, @tailorings)
        @rules = @weights.merge(selected_rules)
        @trie = build_trie(@rules)
        @fingerprint = build_fingerprint(@locale, @selected_locale, @weights_version, @weights,
                                           selected_rules, @variable_code_points.to_a.sort,
                                           @strength, @numeric, @ignore_punctuation)
      end

      def sort_key(string)
        text = normalize_text(string)
        elements = collation_elements(text)
        levels = [[], [], []]

        elements.each do |primary, secondary, tertiary|
          levels[0] << primary if primary != 0
          levels[1] << secondary if @strength >= 2
          levels[2] << tertiary if @strength >= 3
        end

        SortKey.new(@fingerprint, levels[0...@strength], @locale)
      end

      def compare(left, right)
        result = sort_key(left) <=> sort_key(right)
        result <=> 0
      end
      alias_method :collation_key, :sort_key

      def collate(values)
        values.each_with_index
          .map { |value, index| [sort_key(value.to_s), index, value] }
          .sort { |left, right| (left[0] <=> right[0]).nonzero? || left[1] <=> right[1] }
          .map(&:last)
      end
      alias_method :sort, :collate

      def for(locale: @locale, strength: @strength, numeric: @numeric,
              ignore_punctuation: @ignore_punctuation)
        self.class.new(
          locale: locale,
          weights: reconstruct_weights,
          tailorings: @tailorings,
          strength: strength,
          numeric: numeric,
          ignore_punctuation: ignore_punctuation
        )
      end

      def numeric?
        @numeric
      end

      def ignore_punctuation?
        @ignore_punctuation
      end

      private

      def reconstruct_weights
        {
          version: @weights_version,
          variable: @variable_code_points.to_a,
          mappings: @weights
        }
      end

      def collation_elements(text)
        elements = []
        index = 0

        while index < text.length
          character = text[index]

          if @numeric && decimal_digit?(character)
            digits = consume_digits(text, index)
            append_numeric_elements(elements, digits)
            index += digits.length
            next
          end

          if ignored_variable?(character)
            index += 1
            next
          end

          rule, size = find_rule(text, index)
          unless rule
            code_point = "U+#{character.ord.to_s(16).upcase}"
            raise UndefinedWeight, "missing collation weight for #{character.inspect} (#{code_point})"
          end

          elements.concat(rule)
          index += size
        end

        elements
      end

      def consume_digits(text, start)
        index = start
        index += 1 while index < text.length && decimal_digit?(text[index])
        text[start...index]
      end

      def decimal_number(digits)
        Integer(digits, 10)
      end

      def append_numeric_elements(elements, digits)
        number = decimal_number(digits)
        elements << [numeric_primary, 0, 0]
        encode_positive_integer(number).each { |weight| elements << [weight, 0, 0] }
        encode_positive_integer(digits.length).each { |weight| elements << [weight, 0, 0] }
      end

      def numeric_primary
        zero_rule = @rules[[0x30]]
        unless zero_rule
          raise InvalidTable, 'numeric collation requires a weight for ASCII digit 0'
        end

        zero_rule.first[0]
      end

      def encode_positive_integer(number)
        digits = []
        current = number
        if current.zero?
          digits << 0
        else
          until current.zero?
            digits.unshift(current % 255)
            current /= 255
          end
        end

        digits.map { |digit| digit + 1 }.unshift(digits.length + 1)
      end

      def decimal_digit?(character)
        character.ord >= 0x30 && character.ord <= 0x39
      end

      def ignored_variable?(character)
        return false unless @ignore_punctuation

        @variable_code_points.include?(character.ord) ||
          character =~ /\A[\p{P}\p{Z}]\z/
      end

      def find_rule(text, index)
        node = @trie
        match = nil
        size = 0
        cursor = index

        while cursor < text.length && node.is_a?(::Hash) && node.key?(text[cursor])
          node = node[text[cursor]]
          cursor += 1
          if node.is_a?(::Hash) && node.key?(END_OF_RULE)
            match = node[END_OF_RULE]
            size = cursor - index
          end
        end

        [match, size]
      end

      def build_trie(rules)
        rules.each_with_object({}) do |(key, value), trie|
          node = trie
          key.each { |code_point| node = node[code_point.chr(::Encoding::UTF_8)] ||= {} }
          node[END_OF_RULE] = value
        end
      end

      def normalize_text(string)
        raise InvalidString, 'collation input must be a String' unless string.is_a?(::String)

        text = string.dup.force_encoding(::Encoding::UTF_8)
        unless text.valid_encoding?
          raise InvalidTable, "collation input must be valid UTF-8: #{string.inspect}"
        end

        text.unicode_normalize(:nfd)
      end

      def normalize_rules(rules)
        return {} if rules.nil?
        unless rules.is_a?(::Hash)
          raise InvalidTable, 'collation rules must be provided as a Hash'
        end

        rules.each_with_object({}) do |(key, value), normalized|
          normalized[normalize_key(key)] = normalize_value(value)
        end
      end

      def normalize_key(key)
        text = case key
               when ::Integer then key.chr(::Encoding::UTF_8)
               when ::Array then key.map { |part| code_point_from(part) }.pack('U*')
               when ::Symbol then key.to_s
               else key.to_s
               end
        text.unicode_normalize(:nfd).unpack('U*')
      end

      def code_point_from(part)
        case part
        when ::Integer then part
        when ::String, /\A\h{4,6}\z/ then part.to_i(16)
        else part.to_s.ord
        end
      end

      def normalize_value(value)
        case value
        when nil
          []
        when ::String
          UCATable.parse_collation_elements(value)
        when ::Array
          if three_integers?(value)
            [value.map(&:to_i)]
          else
            value.map do |element|
              element = UCATable.parse_collation_elements(element) if element.is_a?(::String)
              raise InvalidTable, "invalid collation element #{element.inspect}" unless three_integers?(element)
              element.map(&:to_i)
            end
          end
        else
          raise InvalidTable, "invalid collation rule #{value.inspect}"
        end
      end

      def three_integers?(value)
        value.is_a?(::Array) && value.length == 3 && value.all? { |item| item.is_a?(::Integer) }
      end

      def extract_variables(weights)
        Array(weights[:variable] || weights[:variables]).flat_map do |variable|
          normalize_key(variable)
        end
      end

      def normalize_tailorings(tailorings)
        return {} if tailorings.nil?
        unless tailorings.is_a?(::Hash)
          raise InvalidTable, 'locale tailorings must be provided as a Hash'
        end

        tailorings.each_with_object({}) do |(locale, rules), normalized|
          normalized[normalize_locale(locale)] = normalize_rules(rules)
        end
      end

      def select_tailoring(locale, tailorings)
        locale_fallback(locale).each do |candidate|
          return [candidate, tailorings[candidate]] if tailorings.key?(candidate)
        end
        [:root, {}]
      end

      def locale_fallback(locale)
        parts = locale.to_s.split('_')
        parts.length.downto(1).map { |count| parts.first(count).join('_').to_sym }
      end

      def normalize_locale(locale)
        locale.to_s.tr('-', '_').downcase.to_sym
      end

      def build_fingerprint(locale, selected_locale, version, weights, tailoring, variables,
                            strength, numeric, ignore_punctuation)
        payload = {
          schema: 'i18n-collation-v1',
          locale: locale,
          selected_locale: selected_locale,
          version: version,
          weights: sort_rules(weights),
          tailoring: sort_rules(tailoring),
          variables: variables,
          strength: strength,
          numeric: numeric,
          ignore_punctuation: ignore_punctuation
        }
        Digest::SHA256.hexdigest(canonicalize(payload))
      end

      def sort_rules(rules)
        rules.sort_by { |key, _| key }
      end

      def canonicalize(value)
        case value
        when ::Hash then sort_rules(value).map { |key, item| [canonicalize(key), canonicalize(item)] }.inspect
        when ::Array then value.map { |item| canonicalize(item) }.inspect
        when ::Symbol then value.inspect
        else value.inspect
        end
      end
    end

    module UCATable
      module_function

      def load(path)
        file = path.respond_to?(:to_path) ? path.to_path : path.to_s
        parse(File.read(file, encoding: 'UTF-8'))
      end

      def parse(contents)
        version = contents[/^\s*#.*?(?:tableVersion|version)[\s:=]+([\d.]+)/i, 1] || 'custom'
        mappings = {}
        variables = []

        contents.each_line do |line|
          entry = line.sub(/\s*#.*\z/, '').strip
          next if entry.empty?

          code_points, elements = entry.split(';', 2)
          next unless elements

          points = code_points.strip.split(/\s+/).map { |point| point.to_i(16) }
          next if points.empty? || points.any? { |point| point > 0x10FFFF }
          parsed_elements = parse_collation_elements(elements)
          variable = elements.include?('*')

          source = points.pack('U*')
          mappings[source] = parsed_elements
          variables.concat(points) if variable
        end

        { version: version, variable: variables.uniq, mappings: mappings }
      end

      def parse_collation_elements(value)
        elements = value.to_s.scan(/\[([*.0-9A-Fa-f]+)\]/).flatten
        raise InvalidTable, "invalid collation rule #{value.inspect}" if elements.empty?

        elements.map do |element|
          parts = element.sub(/\A\*/, '').split('.')
          raise InvalidTable, "invalid collation element #{value.inspect}" unless parts.length == 3
          raise InvalidTable, "invalid collation element #{value.inspect}" unless parts.all?(/\A[0-9A-Fa-f]{1,8}\z/)
          numbers = parts.map { |part| part.to_i(16) }
          raise InvalidTable, "invalid collation element #{value.inspect}" if numbers.any? { |number| number > 0xFFFF }
          numbers
        end
      end
    end

    def self.new(**options)
      Collator.new(**options)
    end

    def self.sort_key(string, **options)
      Collator.new(**options).sort_key(string)
    end

    def self.compare(left, right, **options)
      Collator.new(**options).compare(left, right)
    end
  end
end
